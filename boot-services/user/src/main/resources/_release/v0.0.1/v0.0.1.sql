-- 用户表
CREATE TABLE IF NOT EXISTS user_info (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
	created_by VARCHAR(64) NOT NULL DEFAULT 'sys' COMMENT '创建人',
	updated_by VARCHAR(64) NOT NULL DEFAULT 'sys' COMMENT '修改人',
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
	deleted BOOLEAN DEFAULT FALSE COMMENT '是否删除',
	deleted_id BIGINT DEFAULT 0 COMMENT '删除ID',
    code VARCHAR(64) NOT NULL UNIQUE COMMENT '用户编码',
    username VARCHAR(64) NOT NULL UNIQUE COMMENT '用户名',
    password VARCHAR(128) NOT NULL COMMENT '密码',
    email VARCHAR(128) UNIQUE COMMENT '电子邮箱',
    phone_number VARCHAR(16) UNIQUE COMMENT '电话号码',
    first_name VARCHAR(64) COMMENT '名字',
    last_name VARCHAR(64) COMMENT '姓氏',
    date_of_birth DATE COMMENT '出生日期',
    gender CHAR(1) COMMENT '性别（M: 男, F: 女, O: 其他）',
    type ENUM('admin', 'user') DEFAULT 'user' COMMENT '用户类型（admin: 管理员, user: 普通用户）',
    status ENUM('active', 'inactive') DEFAULT 'active' COMMENT '用户状态（active: 激活, inactive: 未激活）',
	last_active_time TIMESTAMP NULL COMMENT '最后活跃时间',
	last_login_time TIMESTAMP NULL COMMENT '最后登录时间',
	last_logout_time TIMESTAMP NULL COMMENT '最后登出时间',
	locked BOOLEAN DEFAULT FALSE COMMENT '是否锁定',
	expire_time DATETIME(6) NULL COMMENT '过期时间',
	enabled BOOLEAN DEFAULT TRUE COMMENT '是否启用',
	version INT DEFAULT 0 COMMENT '版本号',
	UNIQUE (code, deleted_id),
	UNIQUE (username, deleted_id),
	UNIQUE (email, deleted_id),
	UNIQUE (phone_number, deleted_id)
);
